const TOKENS = new Map<string, Row>(VOCAB.map((row) => [row[0].toLowerCase(), row]));

/**
 * Composes a train name in every language from its English form. Unknown
 * tokens are carried through unchanged rather than dropped, so a new train
 * still renders — just untranslated until its words are added above.
 */
export function translitName(english: string): LocalizedText {
  // Keep the en-dash separator used in names like "Chennai–Mysuru Vande Bharat".
  const parts = english.split(/(\s+|–|-)/);

  const out = {} as Record<Locale, string>;
  for (let i = 0; i < LANGS.length; i++) {
    const lang = LANGS[i];
    out[lang] = parts
      .map((part) => {
        if (!part.trim() || part === '–' || part === '-') return part;
        const row = TOKENS.get(part.toLowerCase());
        return row ? row[i] : part;
      })
      .join('');
  }
  return out as LocalizedText;
}
